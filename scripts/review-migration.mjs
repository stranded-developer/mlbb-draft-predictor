// Writes a Supabase migration for a hero-review round from lib/seed.json: the reviewed heroes' full profiles,
// every counter/synergy/item rule involving them, and any rules named with --rules. Safe to re-run.
// Usage: node scripts/review-migration.mjs 006 angela,argus,arlott --rules rank-bias,ally-trait-fit
import fs from "node:fs";
import path from "node:path";

const root = path.join(import.meta.dirname, "..");
const [id, slugList, ...rest] = process.argv.slice(2);
if (!id || !slugList) {
  console.error("usage: node scripts/review-migration.mjs <id> <slug,slug,...> [--rules id,id] [--title text]");
  process.exit(1);
}
const flag = (name) => {
  const i = rest.indexOf(`--${name}`);
  return i >= 0 ? rest[i + 1] : undefined;
};
const heroes = slugList.split(",");
const ruleIds = (flag("rules") ?? "").split(",").filter(Boolean);
const kb = JSON.parse(fs.readFileSync(path.join(root, "lib/seed.json"), "utf8"));

const q = (v) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const lit = (v) => {
  if (v == null) return "null";
  if (typeof v === "boolean" || typeof v === "number") return String(v);
  if (Array.isArray(v)) return `array[${v.map(q).join(", ")}]::text[]`;
  if (typeof v === "object") return `${q(JSON.stringify(v))}::jsonb`;
  return q(v);
};

const L = [`-- ${id}: hero review — ${heroes.join(", ")}. Generated by scripts/review-migration.mjs. Safe to re-run.`, ""];

// Columns added over time; harmless if they already exist.
L.push(
  "alter table hero_profiles",
  "  add column if not exists tier text,",
  "  add column if not exists rank_bias smallint not null default 0,",
  "  add column if not exists strong_vs_types text[] not null default '{}',",
  "  add column if not exists weak_vs_types text[] not null default '{}',",
  "  add column if not exists strong_vs_traits text[] not null default '{}',",
  "  add column if not exists weak_vs_traits text[] not null default '{}',",
  "  add column if not exists good_with_traits text[] not null default '{}';",
  "",
);

const profiles = kb.hero_profiles.filter((h) => heroes.includes(h.slug));
const cols = Object.keys(profiles[0]);
L.push(`insert into hero_profiles (${cols.join(", ")}) values`);
L.push(profiles.map((h) => `  (${cols.map((c) => lit(h[c])).join(", ")})`).join(",\n"));
L.push(`on conflict (slug) do update set ${cols.filter((c) => c !== "slug").map((c) => `${c} = excluded.${c}`).join(", ")};`, "");

const matchups = kb.matchups.filter((m) => heroes.includes(m.counter) || heroes.includes(m.target));
if (matchups.length) {
  L.push("insert into matchups (counter, target, kind, points, status, why) values");
  L.push(matchups.map((m) => `  (${q(m.counter)}, ${q(m.target)}, ${q(m.kind)}, ${lit(m.points)}, ${q(m.status)}, ${q(m.why)})`).join(",\n"));
  L.push("on conflict (counter, target) do update set kind = excluded.kind, points = excluded.points, status = excluded.status, why = excluded.why;", "");
}

const synergies = kb.synergies.filter((s) => heroes.includes(s.hero_a) || heroes.includes(s.hero_b));
if (synergies.length) {
  L.push("insert into synergies (hero_a, hero_b, points, status, why) values");
  L.push(synergies.map((s) => `  (${q(s.hero_a)}, ${q(s.hero_b)}, ${s.points}, ${q(s.status)}, ${q(s.why)})`).join(",\n"));
  L.push("on conflict (hero_a, hero_b) do update set points = excluded.points, status = excluded.status, why = excluded.why;", "");
}

const items = kb.item_advice.filter((i) => heroes.some((h) => i.trigger === `enemy:${h}`));
if (items.length) {
  L.push("insert into item_advice (trigger, item, for_role, status, why) values");
  L.push(items.map((i) => `  (${q(i.trigger)}, ${q(i.item)}, ${q(i.for_role)}, ${q(i.status)}, ${q(i.why)})`).join(",\n"));
  L.push("on conflict (trigger, item) do update set for_role = excluded.for_role, status = excluded.status, why = excluded.why;", "");
}

const rules = kb.rules.filter((r) => ruleIds.includes(r.id));
if (rules.length) {
  L.push("insert into rules (id, weight, status, description) values");
  L.push(rules.map((r) => `  (${q(r.id)}, ${r.weight}, ${q(r.status)}, ${q(r.description)})`).join(",\n"));
  L.push("on conflict (id) do update set weight = excluded.weight, status = excluded.status, description = excluded.description;", "");
}

const name = `${id}_review_${heroes.join("_").replace(/-/g, "")}.sql`;
fs.writeFileSync(path.join(root, "supabase/migrations", name), L.join("\n"));
console.log(`wrote supabase/migrations/${name}`);
