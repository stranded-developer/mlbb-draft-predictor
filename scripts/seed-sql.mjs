// Generates supabase/seed.sql from lib/seed.json. Existing rows are left untouched (on conflict do nothing),
// so re-running never overwrites edits made in the backoffice.
// Usage: node scripts/seed-sql.mjs
import fs from "node:fs";
import path from "node:path";

const root = path.join(import.meta.dirname, "..");
const KB = JSON.parse(fs.readFileSync(path.join(root, "lib/seed.json"), "utf8"));

const lit = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean" || typeof v === "number") return String(v);
  if (Array.isArray(v)) return `array[${v.map(lit).join(", ")}]::text[]`;
  if (typeof v === "object") return `${lit(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const out = ["-- Generated by scripts/seed-sql.mjs from lib/seed.json. Safe to re-run.", ""];
for (const [table, rows] of Object.entries(KB)) {
  if (!rows.length) continue;
  const cols = Object.keys(rows[0]);
  out.push(`insert into ${table} (${cols.join(", ")}) values`);
  out.push(rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(", ")})`).join(",\n"));
  out.push("on conflict do nothing;", "");
}
// Seed values are already on the current scales, so mark one-time rescales as done.
out.push("insert into applied_migrations (id) values ('004-rescale') on conflict do nothing;", "");
fs.writeFileSync(path.join(root, "supabase/seed.sql"), out.join("\n"));
console.log("wrote supabase/seed.sql");
