// Generates supabase/seed.sql from data/knowledge.js. Existing rows are left untouched (on conflict do nothing),
// so re-running never overwrites edits made in the backoffice.
// Usage: node scripts/seed-sql.js
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const src = fs.readFileSync(path.join(root, "data/knowledge.js"), "utf8");
const KB = new Function(`${src}; return KB;`)();

const lit = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean" || typeof v === "number") return String(v);
  if (Array.isArray(v)) return `array[${v.map(lit).join(", ")}]::text[]`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const out = ["-- Generated by scripts/seed-sql.js from data/knowledge.js. Safe to re-run.", ""];
for (const [table, rows] of Object.entries(KB)) {
  if (!rows.length) continue;
  const cols = Object.keys(rows[0]);
  out.push(`insert into ${table} (${cols.join(", ")}) values`);
  out.push(rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(", ")})`).join(",\n"));
  out.push("on conflict do nothing;", "");
}
fs.writeFileSync(path.join(root, "supabase/seed.sql"), out.join("\n"));
console.log("wrote supabase/seed.sql");
